export interface ElementData {
  z: number; // Atomic Number
  symbol: string;
  nameTh: string;
  nameEn: string;
  atomicMass: number;
  group: string; // '1A', '2A', ..., 'Transition'
  period: number; // 1 to 7
  category:
    | 'alkali'
    | 'alkaline_earth'
    | 'transition'
    | 'post_transition'
    | 'metalloid'
    | 'nonmetal'
    | 'halogen'
    | 'noble_gas';
  categoryTh: string;
  state: 'solid' | 'liquid' | 'gas';
  stateTh: string;
  electronConfig: string;
  electronShells: number[]; // e.g. [2, 8, 1] for Bohr model
  valence: number;
  commonIon: string;
  color: string; // Tailwind color token
  funFact: string;
  examTip: string;
  mnemonic?: string;
}

export interface ChemistryMnemonic {
  id: string;
  title: string;
  groupOrTopic: string;
  chant: string;
  elements: string[];
  explanation: string;
  examNote: string;
}

